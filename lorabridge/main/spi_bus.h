#pragma once
// ============================================================
// Общая шина SPI (V2.9)
//
// Раньше каждый драйвер сам звал spi_bus_initialize() — при
// фиксированной сборке это работало, потому что на шине сидел
// ровно один потребитель. Теперь дисплей, тач и радио могут
// оказаться на одном хосте (типовая распайка ILI9341 + XPT2046),
// и второй spi_bus_initialize() вернёт ESP_ERR_INVALID_STATE.
//
// Поэтому — тонкая обёртка: шина поднимается один раз на хост,
// повторный запрос с теми же пинами просто засчитывается.
// ============================================================
#include "driver/spi_master.h"
#include "esp_err.h"

// host: 1 = SPI2_HOST, 2 = SPI3_HOST (как в hwcfg).
esp_err_t spi_bus_acquire(uint8_t host, int sck, int mosi, int miso,
                          int max_transfer_sz, spi_host_device_t *out_host);

// Фактический потолок одной транзакции на уже поднятой шине.
// Тот, кто просил больше, должен резать свои посылки по этому
// размеру: max_transfer_sz задаёт только ПЕРВЫЙ захвативший шину.
int spi_bus_max_transfer(uint8_t host);
